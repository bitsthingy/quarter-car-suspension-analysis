function m = qc_metrics(s,p,scenario,label)
% Positive dynamic tyre force increases normal load; use total force for contact.
% The 60 mm travel allowance is an assumed screen, not a nonlinear stop model.
% RMS: bump 1-8 s; sine/multisine 2-8 s. Peaks/limits: entire record.
if strcmp(scenario,'bump'), first=1; else, first=2; end
use=s.t>=first; tt=s.t(use);
rmsTime=@(v)sqrt(trapz(tt,v(use).^2)/(tt(end)-tt(1)));
Fstatic=(p.ms+p.mu)*p.g;
m=table(string(label),string(scenario),p.ks,p.cs,first,...
    rmsTime(s.accel),max(abs(s.accel)),1000*max(abs(s.travel)),...
    rmsTime(s.dFz),rmsTime(s.dFz)/Fstatic,min(s.Fz),...
    max(abs(s.travel))<=p.travelLimit && min(s.Fz)>0,...
    'VariableNames',{'Configuration','Scenario','ks_Npm','cs_Nspm',...
    'RMS_window_start_s','Body_accel_RMS_mps2','Body_accel_peak_mps2',...
    'Travel_peak_mm','Tyre_dynamic_load_RMS_N','Dynamic_load_coefficient',...
    'Minimum_total_tyre_load_N','Within_assumed_limits'});
end
